// Helper to construct competitor
function makePlayer(
  id: string,
  displayName: string,
  shortName: string,
  num: number,
  teamName: string,
  teamCode: string,
  pos: string,
  score: number,
  helmetColor: string,
  skinTone: string = '#d98c55',
  stats?: Partial<Competitor['stats']>
): Competitor {
  return {
    id,
    sportId: 'nfl',
    displayName,
    shortName: shortName.toUpperCase(),
    uniformNumber: num,
    teamName,
    teamCode: teamCode.toUpperCase(),
    positionGeneric: pos === 'K' ? 'SCORER' : 'OFFENSE',
    position: pos,
    rating: score > 30 ? 99 : score > 20 ? 94 : 88,
    score,
    stats: {
      passingYards: stats?.passingYards || 0,
      rushingYards: stats?.rushingYards || 0,
      touchdowns: stats?.touchdowns || 0,
      primaryMetricLabel: 'Touchdowns',
      primaryMetricValue: stats?.touchdowns || 0,
    },
    badges: score > 25 ? ['flame_aura', 'mvp_trophy'] : ['gold_star'],
    avatar: {
      helmetColor,
      jerseyColor: helmetColor,
      stripeColor: '#ffffff',
      skinTone,
      number: num,
    },
  };
}

